#!/usr/bin/env python3
"""Embeds every .dig circuit into web/circuits.js so the browser simulator
works from GitHub Pages and from a local file:// open alike.

Run again after changing any circuit in Digital:
    python3 tools/build_circuits.py
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "8bit-computer" / "circuits"
files = {p.name: p.read_text(encoding="utf-8") for p in sorted(src.glob("*.dig"))}
out = root / "web" / "circuits.js"
out.write_text("// Generated by tools/build_circuits.py. Do not edit by hand.\n"
               "window.DIG_FILES = " + json.dumps(files, ensure_ascii=False) + ";\n",
               encoding="utf-8")
print(f"wrote {out.relative_to(root)} with {len(files)} circuits")
